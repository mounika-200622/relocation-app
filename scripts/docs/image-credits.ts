/**
 * Writes docs/image-credits.md from prisma/seed/data/photos.json (made by scripts/fetch-photos.ts).
 *
 *   npx tsx scripts/docs/image-credits.ts
 */
import fs from "node:fs";

type Credit = { file: string; title: string; author: string; license: string; source: string };
type Manifest = { homes: Credit[]; places: Record<string, Credit> };

const manifest: Manifest = JSON.parse(fs.readFileSync("prisma/seed/data/photos.json", "utf8"));

// Markdown table cells: keep the text, but never let a "|" or newline break the table.
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();

function row(label: string, c: Credit) {
  return `| ${cell(label)} | [${cell(c.title)}](${c.source}) | ${cell(c.author)} | ${cell(c.license)} | \`${c.file}\` |`;
}

function placeLabel(key: string) {
  const [scope, name] = key.split(":");
  return scope === "country" ? `Country · ${name}` : `${name} (${scope})`;
}

const places = Object.entries(manifest.places).sort(([a], [b]) => a.localeCompare(b));
const lines = [
  "# Image credits",
  "",
  "Every photo in Nira is a real, freely licensed photograph from [Wikimedia Commons](https://commons.wikimedia.org/).",
  "Only CC0, public-domain, CC BY, CC BY-SA and Free Art licences are accepted (`scripts/fetch-photos.ts`).",
  "Credits are also shown on each photo in the app and on the public `/credits` page.",
  "",
  `Generated by \`npx tsx scripts/docs/image-credits.ts\` · ${places.length} place photos · ${manifest.homes.length} room photos.`,
  "",
  "## Countries and cities",
  "",
  "| Place | File | Author | Licence | Served as |",
  "|---|---|---|---|---|",
  ...places.map(([k, c]) => row(placeLabel(k), c)),
  "",
  "## Rooms and homes (demo listings)",
  "",
  "| # | File | Author | Licence | Served as |",
  "|---|---|---|---|---|",
  ...manifest.homes.map((c, i) => row(String(i + 1), c)),
  "",
];

fs.writeFileSync("docs/image-credits.md", lines.join("\n"));
console.log(`wrote docs/image-credits.md (${places.length} places, ${manifest.homes.length} homes)`);
